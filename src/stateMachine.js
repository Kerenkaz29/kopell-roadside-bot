const Conversation = require('./models/Conversation');
const ServiceRequest = require('./models/ServiceRequest');
const Technician = require('./models/Technician');
const { assignTechnician } = require('./dispatch');
const { startSimulation } = require('./statusSimulator');
const { classifyIssue } = require('./ai/classifyIssue');
const { extractVehicleInfo } = require('./ai/extractVehicleInfo');
const { detectCancelIntent } = require('./ai/detectCancelIntent');
const { generateReply } = require('./ai/generateReply');

// Drives one turn of the conversation and returns the reply text(s) to send back.
// Every customer-facing message is generated by the AI from an instruction and
// concrete facts, rather than from fixed template strings.
async function handleMessage(message, client) {
  let convo = await Conversation.findOne({ phone: message.from });

  if (!convo) {
    convo = await Conversation.create({ phone: message.from, state: 'START' });
  }

  switch (convo.state) {
    case 'START': {
      convo.state = 'AWAITING_ISSUE';
      await convo.save();
      const reply = await generateReply('ברכי את הלקוח ושאלי אותו מה קרה לרכב');
      return [reply];
    }

    case 'AWAITING_ISSUE': {
      const result = await classifyIssue(message.text || '');
      if (!result.understood) {
        const reply = await generateReply(
          'לא הבנת מה קרה לרכב מההודעה האחרונה של הלקוח. בקשי ממנה בנימוס לתאר שוב, בכמה מילים, מה קרה לרכב'
        );
        return [reply];
      }
      const { category, summary } = result;
      convo.data.issueType = category;
      convo.data.issueSummary = summary;
      convo.state = 'AWAITING_LOCATION';
      await convo.save();
      const locationAsk = await generateReply(
        'אשרי ללקוח שהבנת מה קרה, ובקשי ממנה לשתף מיקום כדי שנוכל לשלוח טכנאי',
        { תקלה: summary }
      );
      await client.requestLocation(message.from, locationAsk);
      return [];
    }

    case 'AWAITING_LOCATION': {
      if (message.type !== 'location') {
        const reply = await generateReply('בקשי בנימוס מהלקוח לשתף מיקום באמצעות כפתור השיתוף בוואטסאפ, כי זה הכרחי להמשך');
        return [reply];
      }
      convo.data.location = message.location;
      convo.state = 'AWAITING_VEHICLE';
      await convo.save();
      const reply = await generateReply('תודי ללקוח על שיתוף המיקום, ובקשי ממנה מספר רכב ומספר פוליסת ביטוח');
      return [reply];
    }

    case 'AWAITING_VEHICLE': {
      const { vehicleNumber, policyNumber } = await extractVehicleInfo(message.text || '');
      if (!vehicleNumber && !policyNumber) {
        const reply = await generateReply(
          'לא הבנת את ההודעה הקודמת של הלקוח - לא הצלחת לזהות בה מספר רכב או מספר פוליסה. אמרי לה בנימוס שלא הבנת, ובקשי שתכתוב את מספר הרכב ומספר הפוליסה בצורה ברורה'
        );
        return [reply];
      }

      convo.data.vehicleNumber = vehicleNumber || 'לא צוין';
      convo.data.policyNumber = policyNumber || 'לא צוין';
      convo.state = 'DISPATCHED';
      await convo.save();

      const request = await ServiceRequest.create({
        phone: convo.phone,
        issueType: convo.data.issueSummary || convo.data.issueType,
        location: { type: 'Point', coordinates: [convo.data.location.lng, convo.data.location.lat] },
        vehicleNumber: convo.data.vehicleNumber,
        policyNumber: convo.data.policyNumber,
      });

      const assignment = await assignTechnician(request.location);
      if (!assignment) {
        request.status = 'NEW';
        await request.save();
        const reply = await generateReply('הודיעי ללקוח בנימוס שכרגע כל הטכנאים תפוסים, ושניצור קשר ברגע שאחד יתפנה');
        return [reply];
      }

      request.status = 'ASSIGNED';
      request.technicianId = assignment.technician._id;
      request.etaMinutes = assignment.etaMinutes;
      await request.save();
      startSimulation(request._id, client);

      const reply = await generateReply('עדכני את הלקוח ששויך טכנאי ושהוא בדרך אליה, כולל שם הטכנאי וזמן ההגעה המשוער', {
        שם_טכנאי: assignment.technician.name,
        זמן_הגעה_בדקות: assignment.etaMinutes,
      });
      return [reply];
    }

    case 'DISPATCHED': {
      const request = await ServiceRequest.findOne({ phone: convo.phone }).sort({ createdAt: -1 });
      if (!request) {
        const reply = await generateReply('הודיעי ללקוח שלא נמצאה קריאה פעילה, ושתוכל לפתוח קריאה חדשה בהודעה');
        return [reply];
      }

      if (await detectCancelIntent(message.text)) {
        request.status = 'CANCELLED';
        await request.save();
        if (request.technicianId) {
          await Technician.findByIdAndUpdate(request.technicianId, { status: 'AVAILABLE' });
        }
        convo.state = 'START';
        convo.data = {};
        await convo.save();
        const reply = await generateReply('אשרי ללקוח שהפנייה בוטלה, ושתוכל לפנות שוב בעתיד בהודעה חדשה');
        return [reply];
      }

      const reply = await generateReply('עדכני את הלקוח על סטטוס הקריאה הנוכחי שלה וזמן ההגעה המשוער', {
        סטטוס: request.status,
        זמן_הגעה_בדקות: request.etaMinutes,
      });
      return [reply];
    }

    default:
      return [await generateReply('תודי ללקוח על הפנייה')];
  }
}

module.exports = { handleMessage };
